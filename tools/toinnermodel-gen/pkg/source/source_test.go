func TestScan(t *testing.T) {
	dir := t.TempDir()
	writeFile(t, dir, "views.go", `package views

//toinnermodel:gen
type full struct {
	Plain  string
	Kept   *string
	Filter *filter
}

type Filter struct {
	Term string
}

type filter struct {
	Term string
}

type Full struct {
	Plain  string
	Kept   *string
	Filter }
`)

	pkg, err := Scan(dir)
	require.NoError(t, err)
	assert.Equal(t, "views", pkg.Name)

	require.Len(t, pkg.MarkedStructs, 1)
	assert.Equal(t, "full", pkg.MarkedStructs[0].Name)

	full, ok := pkg.StructMap["full"]
	require.True(t, ok)
	assert.Equal(t, []Field{
		{Name: "Plain", Type: "string"},
		{Name: "Kept", Type: "*string"},
		{Name: "Filter", Type: "*filter"},
	}, full.Fields)

	// the target innerModel's embedded Filter arrives as its type's name
	target, ok := pkg.StructMap["Full"]
	require.True(t, ok)
	assert.Equal(t, []Field{
		{Name: "Plain", Type: "string"},
		{Name: "Kept", Type: "*string"},
		{Name: "Filter", Type: "Filter"},
	}, target.Fields)

	_, ok = pkg.StructMap["Missing"]
	assert.False(t, ok)
}

func TestScan_SkipsNonSources(t *testing.T) {
	dir := t.TempDir()
	writeFile(t, dir, "kept.go", `package skip

//toinnermodel:gen
type kept struct {
	Name string
}

type Kept struct {
	Name string
}
`)
	writeFile(t, dir, GeneratedPrefix+"kept.go", `// Code generated by toinnermodel-gen; DO NOT EDIT.

package skip

type generatedOnly struct {
	Name string
}
`)
	writeFile(t, dir, "kept_test.go", `package skip

type testOnly struct {
	Name string
}
`)

	pkg, err := Scan(dir)
	require.NoError(t, err)
	require.Len(t, pkg.MarkedStructs, 1)
	assert.Equal(t, "kept", pkg.MarkedStructs[0].Name)
	_, ok := pkg.StructMap["Kept"]
	assert.True(t, ok)
	for _, name := range []string{"generatedOnly", "testOnly"} {
		_, ok := pkg.StructMap[name]
		assert.False(t, ok, name)
	}
}

func TestScan_NoSources(t *testing.T) {
	_, err := Scan(t.TempDir())
	require.Error(t, err)
	assert.ErrorContains(t, err, "no Go sources")
}

func TestScan_SkipsNonStructs(t *testing.T) {
	dir := t.TempDir()
	writeFile(t, dir, "misc.go", `package misc

const Count = 1

var Name = "n"

func Helper() {}

type Number int

type Alias = string

type kept struct {
	Name string
}
`)

	pkg, err := Scan(dir)
	require.NoError(t, err)
	assert.Equal(t, "misc", pkg.Name)
	assert.Len(t, pkg.StructMap, 1)
	_, ok := pkg.StructMap["kept"]
	assert.True(t, ok)
}

func TestScan_Refusals(t *testing.T) {
	t.Run("a missing dir refuses", func(t *testing.T) {
		_, err := Scan(filepath.Join(t.TempDir(), "missing"))
		require.Error(t, err)
	})

	t.Run("an unparsable source refuses", func(t *testing.T) {
		dir := t.TempDir()
		writeFile(t, dir, "bad.go", `this is not Go`)
		_, err := Scan(dir)
		require.Error(t, err)
	})
}

func writeFile(t *testing.T, dir, name, content string) {
	t.Helper()
	require.NoError(t, os.WriteFile(filepath.Join(dir, name), []byte(content), osutil.File))
}
